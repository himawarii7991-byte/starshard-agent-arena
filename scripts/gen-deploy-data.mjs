// Generate site/arena/deploy-data.js from the compiled contract bytecode.
// Single source of truth: build/contracts_StarshardArena_sol_StarshardArena.bin
// (solc 0.8.38, optimizer 200 runs). The hex is NEVER hand-typed into the
// site — re-run this script after every recompile.
//
// Usage: node scripts/gen-deploy-data.mjs   (from the project root)
//
// Output: site/arena/deploy-data.js exporting
//   DEPLOY_CREATION_BYTECODE  — "0x"-prefixed creation bytecode (no ctor arg)
//   DEPLOY_CREATION_BYTES     — creation bytecode size in bytes (2,420)
//   DEPLOY_ESTIMATED_GAS      — measured deploy gas on a local Hardhat
//                               network (543,565). The page re-reads live
//                               gas price; this is only the gas estimate.
//   DEPLOY_DATA_BYTES         — full deployment calldata size (2,452):
//                               creation bytecode + 32-byte constructor arg
//   buildDeployData(registry) — creation bytecode + ABI-encoded registry
//                               address (left-padded 32-byte word).

import { readFile, writeFile } from "node:fs/promises";

const BIN_PATH = "build/contracts_StarshardArena_sol_StarshardArena.bin";
const OUT_PATH = "site/arena/deploy-data.js";

const EXPECTED_CREATION_BYTES = 2420;
const MEASURED_DEPLOY_GAS = 543565;

const raw = (await readFile(BIN_PATH, "utf8")).trim();
if (!/^[0-9a-fA-F]+$/.test(raw)) {
  throw new Error(`gen-deploy-data: ${BIN_PATH} is not clean hex`);
}
if (raw.length % 2 !== 0) {
  throw new Error(`gen-deploy-data: ${BIN_PATH} has odd hex length`);
}
const creationBytes = raw.length / 2;
if (creationBytes !== EXPECTED_CREATION_BYTES) {
  throw new Error(
    `gen-deploy-data: creation bytecode is ${creationBytes} bytes, expected ${EXPECTED_CREATION_BYTES} — contract was recompiled with different settings; update EXPECTED_CREATION_BYTES and DEPLOY_ESTIMATED_GAS (re-measure with scripts/gas-report.js) before regenerating`,
  );
}

const out = `// GENERATED by scripts/gen-deploy-data.mjs — do not hand-edit.
// Source: build/contracts_StarshardArena_sol_StarshardArena.bin
// (StarshardArena, solc 0.8.38, optimizer on, 200 runs).
// Constructor takes ONE argument: the Agent ID registry address.
// The page appends it at deploy time via buildDeployData() — the
// registry address itself lives in site/arena/config.js, so the same
// bytecode works on mainnet (real registry) and in local tests (mock).

export const DEPLOY_CREATION_BYTECODE = "0x${raw.toLowerCase()}";
export const DEPLOY_CREATION_BYTES = ${creationBytes};
export const DEPLOY_ESTIMATED_GAS = ${MEASURED_DEPLOY_GAS};
export const DEPLOY_DATA_BYTES = ${creationBytes + 32};

/** Full deployment calldata: creation bytecode + ABI-encoded registry address. */
export function buildDeployData(registryAddress) {
  const addr = String(registryAddress || "")
    .toLowerCase()
    .replace(/^0x/, "");
  if (!/^[0-9a-f]{40}$/.test(addr)) {
    throw new Error("buildDeployData: bad registry address " + registryAddress);
  }
  return DEPLOY_CREATION_BYTECODE + "000000000000000000000000" + addr;
}
`;

await writeFile(OUT_PATH, out);
console.log(
  `gen-deploy-data: wrote ${OUT_PATH} (creation ${creationBytes} bytes, deploy data ${creationBytes + 32} bytes, estimated gas ${MEASURED_DEPLOY_GAS})`,
);
